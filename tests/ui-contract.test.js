import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";

const content = fs.readFileSync(new URL("../content/content.js", import.meta.url), "utf8");
const popup = fs.readFileSync(new URL("../popup/popup.html", import.meta.url), "utf8");
const manifest = JSON.parse(fs.readFileSync(new URL("../manifest.json", import.meta.url), "utf8"));

test("ships the global appearance controls in the pinned extension popup", () => {
  for (const id of ["accentColor", "textColor", "fontFamily", "backgroundOpacity", "gridOpacity", "numberColorMode", "reachedColor"]) {
    assert.match(popup, new RegExp(`id=["']${id}["']`));
  }
});

test("supports multiple sources, source pages, layouts, and auto-saving editors", () => {
  assert.match(content, /data-action="add-source"/);
  assert.match(content, /name="widgetSourceView"/);
  assert.match(content, /function layoutsPageMarkup/);
  assert.match(content, /function autoSaveEditor/);
  assert.doesNotMatch(content, /data-action="save-widget"/);
  assert.doesNotMatch(content, /function sourceForType/);
});

test("packages widget utilities before the content script", () => {
  assert.equal(manifest.version, "0.8.0");
  assert.deepEqual(manifest.content_scripts[0].js, ["lib/widget-utils.js", "content/content.js"]);
});

test("supports multiple player cards and automatic Kalshi portfolio bet imports", () => {
  for (const feature of ["seenPlayerPresets", "espnPlayerCandidates", "syncAccountBetWidgets", "autoGenerated", "autoMappingLocked", "importedAccountItemKeys"]) {
    assert.match(content, new RegExp(feature));
  }
});

test("ships layer sizing, visual presets, Kalshi charts, player numbers, and numeric animation", () => {
  for (const feature of ["name=\"height\"", "name=\"visualStyle\"", "name=\"blockSize\"", "marketChartMarkup", "showPlayerNumber", "animateWidgetNumbers", "ll-resize-height"]) {
    assert.match(content, new RegExp(feature));
  }
});
